#include "push_swap.h"

void	ft_swap(int *a, int *b)
{
	int	tmp;

	tmp = *a;
	*a = *b;
	*b = tmp;
}

void	insertion_sort(int *tab, int size)
{
	int	i;
	int	j;

	i = 1;
	while (i < size)
	{
		j = i;
		while (j > 0 && tab[j] < tab[j - 1])
		{
			ft_swap(&tab[j], &tab[j - 1]);
			j--;
		}
		i++;
	}
}

int	floor_sqrt(int n)
{
	int	i;

	if (n <= 0)
		return (0);
	i = 1;
	while (i * i <= n)
		i++;
	return (i - 1);
}

int	get_chunk_size(int size, int pct)
{
	int	root;

	root = floor_sqrt(size);
	return (root * pct / 100);
}
